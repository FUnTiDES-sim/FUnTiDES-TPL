# Set your TPL installation path (the --prefix given to install.sh)
export TPL_PREFIX="$HOME/test"  # CHANGE THIS to your installation path

# Load the environment script generated by install.sh (PATH, LD_LIBRARY_PATH,
# CMAKE_PREFIX_PATH, Python venv). It does not duplicate entries.
if [ -f "${TPL_PREFIX}/setup_env.sh" ]; then
    source "${TPL_PREFIX}/setup_env.sh" > /dev/null
fi

# Optional: Create an alias to reload TPL environment
alias load-tpl='source "${TPL_PREFIX}/setup_env.sh"'

